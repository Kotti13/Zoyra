// Regenerates THIRD-PARTY-NOTICES.md from package-lock.json. Run: node scripts/gen-notices.js
const fs = require('fs');
const lock = require('../package-lock.json');
const pkg = require('../package.json');
const direct = new Set(Object.keys(pkg.dependencies || {}));
const rows = new Map();
for (const [k, v] of Object.entries(lock.packages)) {
  if (!k || v.dev) continue;
  const name = k.replace(/^.*node_modules\//, '');
  rows.set(`${name}@${v.version}`, { name, version: v.version, license: String(v.license || 'UNKNOWN') });
}
const list = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
const counts = {};
list.forEach((r) => (counts[r.license] = (counts[r.license] || 0) + 1));
const out = [];
out.push('# Third-party notices', '',
  'Zoyra includes the open-source software below. Each package remains under its own licence; the licence',
  'text and copyright notice ship in the package folder (`node_modules/<name>/LICENSE`). Generated by',
  '`node scripts/gen-notices.js` from `package-lock.json` (production dependencies only). Re-run after dependency changes.', '',
  '## Licence summary (production npm packages)', '', '| Licence | Packages |', '|---|---|');
Object.entries(counts).sort((a, b) => b[1] - a[1]).forEach(([l, n]) => out.push(`| ${l} | ${n} |`));
out.push('', '## Native SDKs and services (not in npm licence data)', '',
  '- **Agora RTC SDK** (via `react-native-agora`, MIT wrapper): the native SDK is proprietary, used under the Agora Terms of Service.',
  '- **RevenueCat** (`react-native-purchases`): MIT wrapper; service under RevenueCat Terms.',
  '- **Supabase**, **Sentry**: client libraries MIT; services under their own terms.',
  '- **NewPipe Extractor** (`services/newpipe`, backend only): GPL-3.0. If that service is distributed to anyone, its source must be offered under GPL-3.0. Streaming YouTube content also conflicts with the YouTube Terms of Service and app-store rules.',
  '- **Fonts**: Inter and JetBrains Mono under the SIL Open Font License 1.1.',
  '- **Build tools only (not shipped in the app)**: `@sentry/cli` is FSL-1.1-MIT.', '',
  '## Direct dependencies', '', '| Package | Version | Licence |', '|---|---|---|');
list.filter((r) => direct.has(r.name)).forEach((r) => out.push(`| ${r.name} | ${r.version} | ${r.license} |`));
out.push('', '## All production dependencies', '', '| Package | Version | Licence |', '|---|---|---|');
list.forEach((r) => out.push(`| ${r.name} | ${r.version} | ${r.license} |`));
fs.writeFileSync(__dirname + '/../THIRD-PARTY-NOTICES.md', out.join('\n') + '\n');
console.log('wrote', list.length, 'packages');
